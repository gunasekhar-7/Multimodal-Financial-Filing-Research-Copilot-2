from enum import Enum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from src.schemas.financial import DataSource


class VisualArtifactType(str, Enum):
    BAR_CHART = "bar_chart"
    LINE_CHART = "line_chart"
    FINANCIAL_TABLE = "financial_table"
    BREAKDOWN = "breakdown"


class VisualArtifact(BaseModel):
    model_config = ConfigDict(extra="ignore")
    artifact_id: str
    title: str
    artifact_type: VisualArtifactType
    caption: str
    svg_content: str | None = None
    data_table: dict[str, Any] | None = None
    mime_type: str = "image/svg+xml"


class ClaimVerificationStatus(str, Enum):
    VERIFIED = "verified"
    UNVERIFIED = "unverified"
    CONTRADICTED = "contradicted"
    AMBIGUOUS = "ambiguous"


class Citation(BaseModel):
    model_config = ConfigDict(extra="ignore")
    citation_id: str
    ticker: str
    filing_type: str
    fiscal_year: int
    fiscal_period: str
    page_number: int
    item_section: str
    source_url: str
    excerpt: str
    data_source: DataSource = DataSource.DEMO


class VerifiedClaim(BaseModel):
    model_config = ConfigDict(extra="ignore")
    claim_id: str
    claim_text: str
    numerical_value: float | None = None
    expected_xbrl_value: float | None = None
    status: ClaimVerificationStatus
    verification_notes: str
    citations: list[Citation] = []


class FinancialMetricComparison(BaseModel):
    model_config = ConfigDict(extra="ignore")
    metric_name: str
    concept: str
    unit: str = "USD"
    periods: dict[str, float]  # e.g. {"2023-Q1": 100.0, "2024-Q1": 115.0}
    yoy_change_pct: float | None = None
    qoq_change_pct: float | None = None
    notes: str | None = None


class RiskFactorAnalysis(BaseModel):
    model_config = ConfigDict(extra="ignore")
    category: str
    risk_title: str
    description: str
    trend: str  # e.g., "new", "escalating", "stable", "diminishing"
    citations: list[Citation] = []


class ResearchReport(BaseModel):
    model_config = ConfigDict(extra="ignore")
    report_id: str
    question: str
    target_tickers: list[str]
    executive_summary: str
    metric_comparisons: list[FinancialMetricComparison] = []
    risk_analysis: list[RiskFactorAnalysis] = []
    claims: list[VerifiedClaim] = []
    citations: list[Citation] = []
    visual_artifacts: list[VisualArtifact] = Field(default_factory=list)
    uncertainty_disclosures: list[str] = []
    disclaimer: str = (
        "This report is generated by an AI research tool for informational purposes only "
        "and does not constitute investment advice."
    )
    generated_at: str
    data_mode: str = "demo"
    data_sources: list[DataSource] = []
