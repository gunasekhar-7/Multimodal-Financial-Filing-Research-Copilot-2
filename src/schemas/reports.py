from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field, ConfigDict
from enum import Enum

class ClaimVerificationStatus(str, Enum):
    VERIFIED = "verified"
    UNVERIFIED = "unverified"
    CONTRADICTED = "contradicted"
    AMBIGUOUS = "ambiguous"

class Citation(BaseModel):
    model_config = ConfigDict(extra='ignore')
    citation_id: str
    ticker: str
    filing_type: str
    fiscal_year: int
    fiscal_period: str
    page_number: int
    item_section: str
    source_url: str
    excerpt: str

class VerifiedClaim(BaseModel):
    model_config = ConfigDict(extra='ignore')
    claim_id: str
    claim_text: str
    numerical_value: Optional[float] = None
    expected_xbrl_value: Optional[float] = None
    status: ClaimVerificationStatus
    verification_notes: str
    citations: List[Citation] = []

class FinancialMetricComparison(BaseModel):
    model_config = ConfigDict(extra='ignore')
    metric_name: str
    concept: str
    unit: str = "USD"
    periods: Dict[str, float] # e.g. {"2023-Q1": 100.0, "2024-Q1": 115.0}
    yoy_change_pct: Optional[float] = None
    qoq_change_pct: Optional[float] = None
    notes: Optional[str] = None

class RiskFactorAnalysis(BaseModel):
    model_config = ConfigDict(extra='ignore')
    category: str
    risk_title: str
    description: str
    trend: str # e.g., "new", "escalating", "stable", "diminishing"
    citations: List[Citation] = []

class ResearchReport(BaseModel):
    model_config = ConfigDict(extra='ignore')
    report_id: str
    question: str
    target_tickers: List[str]
    executive_summary: str
    metric_comparisons: List[FinancialMetricComparison] = []
    risk_analysis: List[RiskFactorAnalysis] = []
    claims: List[VerifiedClaim] = []
    citations: List[Citation] = []
    uncertainty_disclosures: List[str] = []
    disclaimer: str = "This report is generated by an AI research tool for informational purposes only and does not constitute investment advice."
    generated_at: str
